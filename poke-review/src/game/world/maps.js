/** 맵이 직사각형인지 검사 — 줄 길이가 어긋나면 렌더링이 통째로 어긋난다 */
export function validateMaps(maps = MAPS) {
  const problems = [];
  for (const map of Object.values(maps)) {
    const w = map.rows[0].length;
    map.rows.forEach((row, i) => {
      if (row.length !== w) problems.push(`${map.id}: ${i}번 줄 길이 ${row.length} (기대 ${w})`);
    });
    const spawnRow = map.rows[map.spawn.y];
    if (!spawnRow || !spawnRow[map.spawn.x]) problems.push(`${map.id}: spawn 좌표가 맵 밖`);
    for (const w2 of map.warps) {
      if (!maps[w2.to]) problems.push(`${map.id}: 워프 대상 '${w2.to}' 없음`);
    }
  }
  return problems;
}
